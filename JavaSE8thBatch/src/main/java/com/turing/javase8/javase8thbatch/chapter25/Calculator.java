    void compute()
    {
        String input = this.txtResult.getText();
        String[]data = input.split("[/+-/*//]");
        int a = Integer.parseInt(data[0]);
        int b = Integer.parseInt(data[1]);
        
        int result =0;
        if(input.contains("+"))
        {
            result = a + b;
        }
        else if(input.contains("-"))
        {
            result = a - b;
        }
        else if(input.contains("*"))
        {
            result = a * b;
        }
        else if(input.contains("/"))
        {
            result = a / b;
        }
        this.txtResult.setText(""+result);
    }
