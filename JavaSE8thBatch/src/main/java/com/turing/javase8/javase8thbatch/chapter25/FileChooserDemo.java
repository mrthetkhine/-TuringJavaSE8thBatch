    private void btnBrowseActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBrowseActionPerformed
        // TODO add your handling code here:
        SwingUtilities.invokeLater(() -> {
            //JFileChooser chooser = new JFileChooser();
            this.fileChooser.setVisible(true);
            if(fileChooser.showOpenDialog(null) == JFileChooser.APPROVE_OPTION)
            {
                System.out.println("Open "+fileChooser.getSelectedFile());
                String file = fileChooser.getSelectedFile().getAbsolutePath();
                this.txtFileName.setText(file);
                try { 
                    List<String> lines = Files.readAllLines(Path.of(file));
                    StringBuffer buffer = new StringBuffer();
                    for(String line:lines)
                    {
                        buffer.append(line+"\r\n");
                    }
                    this.txtContent.setText(buffer.toString());
                } catch (IOException ex) {
                    Logger.getLogger(FileChooserDemo.class.getName()).log(Level.SEVERE, null, ex);
                }
            }
            this.fileChooser.setVisible(false);
            // Process the result...
        });
        
    }//GEN-LAST:event_btnBrowseActionPerformed

    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        // TODO add your handling code here:
        this.fileChooser.setVisible(true);
        if(fileChooser.showSaveDialog(null) == JFileChooser.APPROVE_OPTION)
        {
            System.out.println("Save "+fileChooser.getSelectedFile());
            File file = fileChooser.getSelectedFile();
            String content = this.txtContent.getText();
            try(DataOutputStream dout=new DataOutputStream(new FileOutputStream(file)) ) { 
                dout.writeBytes(content);
            } catch (Exception ex) {
                Logger.getLogger(FileChooserDemo.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
        this.fileChooser.setVisible(false);
    }//GEN-LAST:event_btnSaveActionPerformed

