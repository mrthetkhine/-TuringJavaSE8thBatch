    private void btnRemoveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoveActionPerformed
        // TODO add your handling code here:
        int row = this.tblList.getSelectedRow();
        if(row==-1)
        {
            JOptionPane.showMessageDialog(null, "No row selected");
        }
        else
        {
            if(JOptionPane.showConfirmDialog(this, "Are you sure to delete",
                    "Delete",JOptionPane.YES_NO_OPTION) == JOptionPane.YES_OPTION)
            {
                DefaultTableModel model = (DefaultTableModel)this.tblList.getModel();
                model.removeRow(row);
            }
            
        }
    }//GEN-LAST:event_btnRemoveActionPerformed

