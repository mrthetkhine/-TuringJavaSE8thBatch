    void addRow()
    {
        Object[] row = new Object[4];
        row[0] = this.txtName.getText();
        row[1]=this.txtPrice.getText();
        row[2] = this.txtQty.getText();
        int total = Integer.parseInt(this.txtPrice.getText())* Integer.parseInt(this.txtQty.getText());
        row[3] = total+"";
        
        DefaultTableModel model = (DefaultTableModel)this.tblList.getModel();
        model.addRow(row);
        
        this.txtName.setText("");
        this.txtPrice.setText("");
        this.txtQty.setText("");
        
    
    }
